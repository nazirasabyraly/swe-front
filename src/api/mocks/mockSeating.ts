import type { EventsApi } from '../events';
import { SEATING_ERRORS, type SeatingApi, type SeatingConfig, type SeatMap, type VenueLayout } from '../seating';
import type { MockTicketTypesApi } from './mockTicketTypes';
import { mockDelay, mockError } from './util';

/**
 * In-browser stand-in for assigned seating. One predefined layout (SRS 4.3.1 asks for at least one).
 * Holds are keyed by checkout reservation; a seat can't be held or sold twice.
 */

function buildLayout(): VenueLayout {
  const rows = (prefix: string, labels: string[], perRow: number, category: string, accessible: (row: string, n: number) => boolean) =>
    labels.map((label) => ({
      label,
      seats: Array.from({ length: perRow }, (_, i) => ({
        id: `${prefix}-${label}-${i + 1}`,
        number: String(i + 1),
        category,
        accessible: accessible(label, i + 1),
      })),
    }));
  const sections = [
    { id: 'PAR', name: 'Parterre', rows: rows('PAR', ['A', 'B', 'C', 'D', 'E', 'F'], 16, 'standard', (r, n) => r === 'A' && (n <= 2 || n >= 15)) },
    { id: 'BAL', name: 'Balcony', rows: rows('BAL', ['A', 'B', 'C', 'D'], 12, 'premium', () => false) },
  ];
  return {
    id: 'hall-a',
    name: 'Concert hall A (144 seats)',
    description: 'Parterre: 6 rows × 16 seats with 4 wheelchair-accessible places in row A. Balcony: 4 rows × 12 seats.',
    seatCount: 144,
    categories: [
      { id: 'standard', label: 'Parterre' },
      { id: 'premium', label: 'Balcony' },
    ],
    sections,
  };
}

const LAYOUTS = [buildLayout()];

export interface MockSeatingApi extends SeatingApi {
  /** Mock-only: holds seats for a checkout reservation. Throws `seat_unavailable`. */
  hold(eventId: string, seatIds: string[], holdId: string): Promise<void>;
  release(holdId: string): void;
  /** Marks held seats sold and returns their labels, in the order they were held. */
  sell(holdId: string): { seatId: string; section: string; row: string; seat: string; ticketTypeId: string }[];
}

interface SeedConfig {
  layoutId: string;
  /** category → ticket type *name* (ids are generated by the ticket-type mock) */
  categories: Record<string, string>;
  sold: string[];
}

/** The seeded "Winter Gala" uses assigned seating with a few seats already sold. */
const SEED: Record<string, SeedConfig> = {
  'evt-winter-gala': {
    layoutId: 'hall-a',
    categories: { standard: 'Parterre', premium: 'Balcony' },
    sold: [
      ...['C', 'D'].flatMap((r) => Array.from({ length: 10 }, (_, i) => `PAR-${r}-${i + 4}`)),
      ...Array.from({ length: 10 }, (_, i) => `BAL-A-${i + 2}`),
    ],
  },
};

export function createMockSeatingApi(deps: { events: EventsApi; ticketTypes: MockTicketTypesApi }, seed = SEED): MockSeatingApi {
  const configs = new Map<string, SeatingConfig>();
  const sold = new Map<string, Set<string>>();
  const holds = new Map<string, { eventId: string; seatIds: string[] }>();
  const seeded = new Set<string>();

  async function config(eventId: string): Promise<SeatingConfig> {
    await deps.events.getEvent(eventId);
    if (!seeded.has(eventId)) {
      seeded.add(eventId);
      const s = seed[eventId];
      if (s) {
        const types = await deps.ticketTypes.listTicketTypes(eventId);
        const mapping = Object.fromEntries(
          Object.entries(s.categories).map(([cat, name]) => [cat, types.find((t) => t.name === name)?.id ?? '']),
        );
        configs.set(eventId, { mode: 'assigned', layoutId: s.layoutId, categoryTicketTypes: mapping });
        sold.set(eventId, new Set(s.sold));
      }
    }
    return configs.get(eventId) ?? { mode: 'general_admission', layoutId: null, categoryTicketTypes: {} };
  }

  const heldSeats = (eventId: string) =>
    new Set([...holds.values()].filter((h) => h.eventId === eventId).flatMap((h) => h.seatIds));

  async function seatMap(eventId: string): Promise<SeatMap> {
    const cfg = await config(eventId);
    const layout = LAYOUTS.find((l) => l.id === cfg.layoutId);
    if (cfg.mode !== 'assigned' || !layout) return { mode: 'general_admission', layoutName: '', categories: [], sections: [] };
    const types = await deps.ticketTypes.listTicketTypes(eventId);
    const soldSet = sold.get(eventId) ?? new Set();
    const held = heldSeats(eventId);
    return {
      mode: 'assigned',
      layoutName: layout.name,
      categories: layout.categories.map((c) => ({ ...c, ticketTypeId: cfg.categoryTicketTypes[c.id] || null })),
      sections: layout.sections.map((section) => ({
        ...section,
        rows: section.rows.map((row) => ({
          label: row.label,
          seats: row.seats.map((seat) => {
            const type = types.find((t) => t.id === cfg.categoryTicketTypes[seat.category] && !t.hidden);
            const status = !type ? 'unavailable' : soldSet.has(seat.id) ? 'sold' : held.has(seat.id) ? 'held' : 'available';
            return { ...seat, status, ticketTypeId: type?.id ?? null, price: type?.price ?? null };
          }),
        })),
      })),
    };
  }

  return {
    async listLayouts() {
      await mockDelay();
      return structuredClone(LAYOUTS);
    },
    async getSeating(eventId) {
      await mockDelay();
      return structuredClone(await config(eventId));
    },
    async updateSeating(eventId, next) {
      await mockDelay();
      await config(eventId);
      if ((sold.get(eventId)?.size ?? 0) > 0 && JSON.stringify(next) !== JSON.stringify(configs.get(eventId))) {
        throw mockError(409, SEATING_ERRORS.hasSales, 'Seats are already sold, so the seating plan can’t change.');
      }
      if (next.mode === 'assigned' && !LAYOUTS.some((l) => l.id === next.layoutId)) {
        throw mockError(422, 'invalid_layout', 'Choose a venue layout.');
      }
      configs.set(eventId, structuredClone(next));
      return structuredClone(next);
    },
    async getSeatMap(eventId) {
      await mockDelay();
      return structuredClone(await seatMap(eventId));
    },
    async hold(eventId, seatIds, holdId) {
      const map = await seatMap(eventId);
      const seats = map.sections.flatMap((s) => s.rows.flatMap((r) => r.seats));
      // Checked and held in one synchronous step, so two checkouts can't take the same seat.
      for (const id of seatIds) {
        const seat = seats.find((s) => s.id === id);
        if (!seat || seat.status !== 'available') {
          throw mockError(409, SEATING_ERRORS.seatUnavailable, 'One of the selected seats was just taken. Choose another seat.');
        }
      }
      holds.set(holdId, { eventId, seatIds: [...seatIds] });
    },
    release(holdId) {
      holds.delete(holdId);
    },
    sell(holdId) {
      const hold = holds.get(holdId);
      if (!hold) return [];
      holds.delete(holdId);
      const set = sold.get(hold.eventId) ?? new Set<string>();
      sold.set(hold.eventId, set);
      const layout = LAYOUTS.find((l) => l.id === configs.get(hold.eventId)?.layoutId)!;
      return hold.seatIds.map((seatId) => {
        set.add(seatId);
        for (const section of layout.sections)
          for (const row of section.rows) {
            const seat = row.seats.find((s) => s.id === seatId);
            if (seat) {
              return { seatId, section: section.name, row: row.label, seat: seat.number, ticketTypeId: configs.get(hold.eventId)!.categoryTicketTypes[seat.category] };
            }
          }
        return { seatId, section: '', row: '', seat: seatId, ticketTypeId: '' };
      });
    },
  };
}
